def add_notes(source: Path, output: Path) -> None:
    prs = Presentation(source)
    if len(prs.slides) != 17:
        raise ValueError(f"Expected 17 slides, found {len(prs.slides)}")

    for slide_number, script in SCRIPTS.items():
        slide = prs.slides[slide_number - 1]
        frame = slide.notes_slide.notes_text_frame
        if frame is None:
            raise RuntimeError(f"Slide {slide_number} has no speaker-notes text frame")
        frame.text = script
        for paragraph in frame.paragraphs:
            for run in paragraph.runs:
                run.font.name = "Noto Sans KR"
                run.font.size = Pt(14)

    output.parent.mkdir(parents=True, exist_ok=True)
    prs.save(output)


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("source", type=Path)
    parser.add_argument("output", type=Path)
    args = parser.parse_args()
    add_notes(args.source, args.output)
    print(args.output)


if __name__ == "__main__":
    main()
